#!/usr/bin/env python3
"""Slice reusable visual elements out of the committed design references into public/images/*.webp.

Only crop + WebP conversion/compression is performed. No new imagery is generated or painted.
Run from the repository root:  python3 scripts/slice-assets.py
It also rewrites docs/DESIGN_ASSET_MANIFEST.md so the manifest always matches the outputs.
"""
import os
from PIL import Image

OPTION3 = 'exec-7a0e29e2-9727-45d9-ad17-9d62027cd564.png'
MODAL_REF = 'docs/design/codex-clipboard-e931d75f-e684-4cc4-916b-cc5572b2c4e5.png'
QUALITY = 82

# name: (source, (left, top, right, bottom), usage)
ASSETS = {
    'logo': (OPTION3, (30, 16, 128, 84), 'Header brand mark'),
    'hero': (OPTION3, (580, 85, 853, 345), 'Hero illustration (Tugu and mountain)'),
    'cat-kost': (OPTION3, (52, 498, 152, 602), '"Cari Kost" category icon'),
    'cat-kontrakan': (OPTION3, (456, 503, 554, 600), '"Cari Kontrakan" category icon'),
    'trust-photo': (OPTION3, (64, 734, 148, 818), 'Trust checklist: minimum 3 photos'),
    'trust-whatsapp': (OPTION3, (301, 734, 385, 818), 'Trust checklist: WhatsApp reachable'),
    'trust-shield': (OPTION3, (573, 734, 657, 818), 'Trust checklist: admin reviewed'),
    'photo-kost': (OPTION3, (40, 964, 348, 1180), 'Kost listing photo'),
    'photo-kontrakan': (OPTION3, (40, 1199, 348, 1424), 'Kontrakan listing photo'),
    'warning-girl': (MODAL_REF, (941, 112, 1272, 482), 'Anti-scam modal and warning card illustration'),
    'footer-art': (OPTION3, (372, 1648, 853, 1844), 'Footer scene'),
}

os.makedirs('public/images', exist_ok=True)
rows = []
for name, (src, box, usage) in ASSETS.items():
    img = Image.open(src).convert('RGB').crop(box)
    out = f'public/images/{name}.webp'
    img.save(out, 'WEBP', quality=QUALITY, method=6)
    rows.append((name, src, box, img.size, os.path.getsize(out), usage))

with open('docs/DESIGN_ASSET_MANIFEST.md', 'w') as f:
    f.write('# Design Asset Manifest\n\n')
    f.write('Generated by `scripts/slice-assets.py`. Every shipped image is a crop of a committed design reference.\n')
    f.write('No image was generated, painted, or sourced elsewhere (handoff: asset and image-generation policy).\n\n')
    f.write(f'Transform for every asset: crop to the box below, convert to RGB, save as WebP quality {QUALITY} (method 6). ')
    f.write('No resizing, color correction, or retouching was applied.\n\n')
    f.write('Sources:\n\n')
    f.write(f'- `{OPTION3}` (Option 3 reference, 853x1844)\n')
    f.write(f'- `{MODAL_REF}` (anti-scam modal reference screenshot, 1308x546)\n\n')
    f.write('| Output | Source | Crop box (l, t, r, b) | Size (px) | Bytes | Usage |\n| --- | --- | --- | --- | --- | --- |\n')
    for name, src, box, size, nbytes, usage in rows:
        f.write(f'| `public/images/{name}.webp` | `{src}` | {box} | {size[0]}x{size[1]} | {nbytes} | {usage} |\n')
    f.write('\nAlt text and loading: decorative images use `alt=""`; below-the-fold images use `loading="lazy"`; ')
    f.write('every `<img>` declares `width` and `height` to prevent layout shift.\n')
    f.write('\nLimits: sources are raster mockups, so crops are limited to their native resolution (listing photos are 308 px wide). ')
    f.write('Replace with real assets before public launch.\n')
print('ok', len(rows), 'assets')
